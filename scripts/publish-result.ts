/**
 * Publish Result — shared "write the verdict to Jira" pipeline.
 *
 * Used by BOTH paths so every ticket gets the same rich output:
 *   - ticket-flow.ts        → after a codified validator produces a ValidationResult
 *   - post-validation.ts    → after the AGENT validates live via the Playwright MCP
 *
 * Responsibilities: publish PASS/FAIL results to Jira. INCONCLUSIVE results are local-only
 * and must not change Jira or any downstream bug pipeline.
 */

import path from 'node:path';
import {
  transitionIssue,
  addComment,
  attachFile,
  getRecentComments,
  getTransitions,
  type JiraIssue,
} from './jira-client.js';
import {
  buildPassComment,
  buildFailComment,
  type ValidationResult,
} from './ticket-validator.js';

const AI_COMMENT_MARKER = '🤖 _This comment was generated by the QA AI Agent';

const TRANSITIONS = {
  inProgress:   'In Progress',
  performance:  'Performance Test',
  inAcceptance: 'In Acceptance',
} as const;

export type Verdict = 'pass' | 'fail' | 'inconclusive';

export interface PublishOptions {
  /** 'QA' | 'CAE' — controls the comment env label. Defaults to APP_ENV or 'QA'. */
  env?: string;
  /** Perform the verdict-based transition. Default true. */
  transition?: boolean;
}

export interface PublishOutcome {
  verdict: Verdict;
  /** Basenames of files that actually uploaded. */
  attached: string[];
  /** Status the ticket was moved to, or null if no/failed transition. */
  movedTo: string | null;
  /** External blocker reason when transition couldn't be performed. */
  blockedReason: string | null;
}

/** Drop the volatile timestamp line so two otherwise-identical comments compare equal. */
export function stripVolatile(body: string): string {
  return body.replace(/_Tested on:.*$/m, '').trim();
}

/** Transition the issue, returning false (with a warning) instead of throwing when the
 *  target transition isn't available from the current status on this board. */
export async function tryTransition(issueKey: string, name: string): Promise<{ ok: boolean; reason: string | null }> {
  try {
    await transitionIssue(issueKey, name);
    return { ok: true, reason: null };
  } catch (err) {
    const m = err instanceof Error ? err.message : String(err);
    console.warn(`[Publish] ⚠️  Could not transition ${issueKey} to "${name}": ${m}`);
    return { ok: false, reason: m };
  }
}

/**
 * Attach all evidence to the issue, robustly. A single failed upload must NOT abort
 * the run or block the comment. Records the basenames that actually uploaded on
 * `result.attachedNames` so the comment only embeds files that really exist.
 * Always call this BEFORE building the comment.
 */
export async function attachEvidence(issueKey: string, result: ValidationResult): Promise<string[]> {
  if (!result.passed && result.inconclusive) {
    result.attachedNames = [];
    console.log(`[Publish] Evidence omitted for inconclusive result on ${issueKey}`);
    return [];
  }

  const files = [
    ...result.screenshots,
    ...(result.networkLogPath ? [result.networkLogPath] : []),
  ];
  const attached: string[] = [];
  for (const file of files) {
    try {
      await attachFile(issueKey, file);
      attached.push(path.basename(file));
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err);
      console.warn(`[Publish] ⚠️  Could not attach ${path.basename(file)}: ${msg}`);
    }
  }
  result.attachedNames = attached;
  console.log(`[Publish] Evidence: ${attached.length}/${files.length} file(s) attached to ${issueKey}`);
  return attached;
}

/**
 * Post the AI comment. Each run should leave a fresh, timestamped verdict (with its
 * evidence), so we only skip when the newest AI comment is byte-identical to this one
 * apart from the timestamp — a truly redundant re-run with the same result.
 */
export async function postCommentOnce(issueKey: string, comment: string): Promise<void> {
  try {
    const recent = await getRecentComments(issueKey, 5); // newest first
    const lastAi = recent.find(body => body.includes(AI_COMMENT_MARKER));
    if (lastAi && stripVolatile(lastAi) === stripVolatile(comment)) {
      console.log(`[Publish] Newest AI comment is identical for ${issueKey} — skipping duplicate`);
      return;
    }
  } catch {
    // If we can't read comments, fall through and post — better a possible dup than no evidence.
  }
  await addComment(issueKey, comment);
}

/** Classify a ValidationResult into a single verdict. */
export function verdictOf(result: ValidationResult): Verdict {
  if (result.passed) return 'pass';
  if (result.inconclusive) return 'inconclusive';
  return 'fail';
}

function isCaePerf(issue: JiraIssue): boolean {
  return issue.labels.some(l =>
    l.toLowerCase().includes('cae-perf') || l.toLowerCase().includes('caeperf')
  );
}

/**
 * Publish a conclusive validation result to Jira: attach evidence → post the verdict comment →
 * transition the ticket. Verdict-driven transitions:
 *   pass         → Performance Test  (or In Acceptance when labelled cae-perf)
 *   fail         → In Progress       (real defect, back to dev)
 *   inconclusive → no Jira interaction; report the blocker to the user and leave the issue unchanged
 * Transitions use tryTransition() so an unavailable transition never crashes.
 */
export async function publishResult(
  issue: JiraIssue,
  result: ValidationResult,
  opts: PublishOptions = {}
): Promise<PublishOutcome> {
  const env = opts.env ?? process.env.APP_ENV ?? 'QA';
  const envLabel = env === 'CAE' ? 'CAE' : 'QA';
  const verdict = verdictOf(result);

  if (verdict === 'inconclusive') {
    const reason = 'INCONCLUSIVE results are local-only; Jira and any downstream bug pipeline were not updated.';
    result.attachedNames = [];
    console.log(`[Publish] ⚠️  ${issue.key} INCONCLUSIVE — ${reason}`);
    return { verdict, attached: [], movedTo: null, blockedReason: reason };
  }

  // 1) Attach evidence before building the comment so it only references uploaded files.
  const attached = await attachEvidence(issue.key, result);

  // 2) Build + post the verdict comment.
  const comment =
    verdict === 'pass' ? buildPassComment(issue, envLabel, result)
    : buildFailComment(issue, envLabel, result);
  await postCommentOnce(issue.key, comment);

  // 3) Transition based on verdict (best-effort).
  let movedTo: string | null = null;
  let blockedReason: string | null = null;
  if (opts.transition !== false) {
    const targets =
      verdict === 'pass'
        ? (isCaePerf(issue) ? [TRANSITIONS.inAcceptance, TRANSITIONS.performance] : [TRANSITIONS.performance, TRANSITIONS.inAcceptance])
        : [TRANSITIONS.inProgress];

    const resolved = await resolveBestTransition(issue.key, targets);
    if (!resolved) {
      blockedReason = `No valid transition available for verdict=${verdict}. Preferred: ${targets.join(' -> ')}`;
      console.warn(`[Publish] ⚠️  ${blockedReason}`);
    } else {
      const tx = await tryTransition(issue.key, resolved);
      if (tx.ok) movedTo = resolved;
      else blockedReason = tx.reason ?? `Could not transition ${issue.key} to ${resolved}`;
    }
  }

  const icon = verdict === 'pass' ? '✅' : '❌';
  console.log(`[Publish] ${icon} ${issue.key} ${verdict.toUpperCase()}${movedTo ? ` → "${movedTo}"` : ''}`);

  return { verdict, attached, movedTo, blockedReason };
}

function normalize(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '');
}

async function resolveBestTransition(issueKey: string, preferred: string[]): Promise<string | null> {
  const findPreferred = (names: string[]): string | null => {
    const byNorm = new Map<string, string>();
    for (const transition of names) byNorm.set(normalize(transition), transition);
    for (const name of preferred) {
      const direct = byNorm.get(normalize(name));
      if (direct) return direct;
    }
    return null;
  };

  let transitions = await getTransitions(issueKey);
  const direct = findPreferred(transitions.map(t => t.name));
  if (direct) return direct;

  // Ready-for-Testing issues may require the In Testing pickup step before a
  // conclusive verdict can move them forward. Never do this before the verdict.
  const pickup = transitions.find(t => normalize(t.name) === normalize('In Testing'));
  if (!pickup) return null;

  const moved = await tryTransition(issueKey, pickup.name);
  if (!moved.ok) return null;

  transitions = await getTransitions(issueKey);
  return findPreferred(transitions.map(t => t.name));
}
