/**
 * Ticket Validator
 * Routes each Jira ticket to its specialized validator.
 * Falls back to the PENDING error for tickets without an implementation.
 */

import path from 'node:path';
import { type Page } from 'playwright';
import { capture } from './screenshot.js';
import { NetworkMonitor, type NetworkEntry } from './network-monitor.js';
import type { JiraIssue } from './jira-client.js';

/** A single acceptance-criterion check, rendered as one row of the AC table. */
export interface AcCheck {
  /** Short id/label, e.g. "AC1" or a test-case id like "C7886423" */
  id?: string;
  /** What this AC requires / what was checked */
  description: string;
  /** Expected behavior */
  expected: string;
  /** What actually happened */
  observed: string;
  passed: boolean;
  /** Optional tri-state; overrides `passed` for the rendered verdict symbol. */
  status?: 'pass' | 'fail' | 'inconclusive';
}

export interface ValidationResult {
  passed: boolean;
  /** The run could NOT confirm the feature (Save blocked/unobserved). Not a dev failure. */
  inconclusive?: boolean;
  summary: string;
  details: string[];
  screenshots: string[];
  networkLogPath: string | null;
  consoleErrors: string[];

  // ── Optional structured fields (used to build richer comments) ───────────────
  /** AC-by-AC results → rendered as a table. Preferred over `details`. */
  acChecks?: AcCheck[];
  /** ACs / areas explicitly NOT covered this run — coverage honesty. */
  notValidated?: string[];
  /** Environment label, e.g. "QA — your-app-qa.example.com" */
  environment?: string;
  /** How the test was run, e.g. "Automated — Playwright over shared Edge (CDP)" */
  method?: string;
  /** Key test data used (field → value) */
  testData?: Record<string, string>;
  /** Record URL / id (order, case, deal…) created during the test, if a single one applies */
  dealUrl?: string;
  /** Numbered repro steps (mainly for FAIL comments) */
  reproSteps?: string[];
  /** Failing network calls (HTTP >= 400) — surfaced inline so a bug-fixing agent
   *  sees the exact endpoint, status and response without opening the JSON. */
  networkCalls?: NetworkEntry[];
  /** Basenames of evidence files actually attached to the issue (set by the flow
   *  AFTER upload), so the comment only embeds images that really exist. */
  attachedNames?: string[];
}

type ValidatorFn = (page: Page, issue: JiraIssue) => Promise<ValidationResult>;

/** Registry of codified ticket validators, keyed by Jira issue key. */
const VALIDATORS: Record<string, ValidatorFn> = {
  // 'PROJ-1234': validatePROJ1234Ticket,
};

/** Whether a codified validator exists for this ticket key. */
export function hasValidator(key: string): boolean {
  return key in VALIDATORS;
}

/**
 * Validate a Jira ticket against the live app.
 * Routes to a specialized validator when one exists for the ticket key.
 */
export async function validateTicket(
  page: Page,
  issue: JiraIssue,
  appUrl: string
): Promise<ValidationResult> {
  // Navigation is handled by each specific validator to avoid MSAL re-init issues

  // ── Route to ticket-specific validators ─────────────────────────────────────
  const validator = VALIDATORS[issue.key];
  if (validator) {
    return validator(page, issue);
  }

  // ── No validator implemented yet ─────────────────────────────────────────────
  const subdir = issue.key;
  const monitor = new NetworkMonitor();
  const consoleErrors: string[] = [];
  const screenshots: string[] = [];

  monitor.attach(page);
  page.on('console', msg => {
    if (msg.type() === 'error') consoleErrors.push(`[error] ${msg.text()}`);
  });

  screenshots.push(await capture(page, `${issue.key}-start`, subdir));

  throw new Error(
    `[PENDING] No validator implemented for ${issue.key}.\n\n` +
    `Validate it live with the Playwright MCP, or add scripts/validators/${issue.key.toLowerCase()}.ts\n` +
    `(built on a page object under scripts/pages/) and register it in ticket-validator.ts.\n\n` +
    `ACs to validate:\n${issue.acceptanceCriteria}`
  );
}

// ─── Comment builders (Jira wiki markup, Data Center API v2) ────────────────────

const AI_FOOTER = `----\n🤖 _This comment was generated by the QA AI Agent (GitHub Copilot). Reviewed by: ${process.env.QA_OWNER_NAME ?? "the QA owner"}._`;

/** Make a string safe to put inside a wiki-markup table cell. */
function cell(text: string): string {
  return (text || '—').replace(/\r?\n/g, ' ').replace(/\|/g, '\\|').trim();
}

/** Render the AC-by-AC results as a wiki-markup table. */
function renderAcTable(checks: AcCheck[]): string[] {
  const rows = checks.map(c => {
    const label = c.id ? `${c.id} — ${c.description}` : c.description;
    const status = c.status ?? (c.passed ? 'pass' : 'fail');
    const verdict = status === 'pass' ? '✅ PASS' : status === 'fail' ? '❌ FAIL' : '⚠️ INCONCLUSIVE';
    return `|${cell(label)}|${cell(c.expected)}|${cell(c.observed)}|${verdict}|`;
  });
  return ['||Acceptance Criterion||Expected||Observed||Result||', ...rows];
}

/** Render the "Test Context" block. */
function renderContext(result: ValidationResult, env: string): string[] {
  const lines = ['h4. Test Context'];
  lines.push(`* *Environment:* ${result.environment ?? env}`);
  if (result.method)  lines.push(`* *Method:* ${result.method}`);
  if (result.dealUrl) lines.push(`* *Record URL:* ${result.dealUrl}`);
  if (result.testData && Object.keys(result.testData).length) {
    const td = Object.entries(result.testData).map(([k, v]) => `${k}: ${v}`).join(', ');
    lines.push(`* *Test data:* ${td}`);
  }
  return lines;
}

/** Render the "Evidence" block — embeds the final screenshot, lists the rest. */
function renderEvidence(result: ValidationResult): string[] {
  // Prefer files that were ACTUALLY attached (set by the flow after upload). Before
  // upload, fall back to the expected basenames so previews still render in tests.
  const all = result.attachedNames ?? [
    ...result.screenshots.map(s => path.basename(s)),
    ...(result.networkLogPath ? [path.basename(result.networkLogPath)] : []),
  ];
  if (!all.length) return [];

  const images = all.filter(n => /\.(png|jpe?g|gif)$/i.test(n));
  const others = all.filter(n => !/\.(png|jpe?g|gif)$/i.test(n));

  const lines: string[] = ['h4. Evidence'];
  if (images.length) {
    for (const img of images) lines.push(`!${img}|thumbnail!`); // embed EVERY screenshot inline as a clickable thumbnail
    lines.push(`_(${images.length} screenshot${images.length === 1 ? '' : 's'} attached)_`);
  }
  for (const o of others) {
    lines.push(`* Attached: {{${o}}}`);
  }
  return lines;
}

/**
 * Render failing network calls inline — the "what & where" a bug-fixing agent needs:
 * exact endpoint, HTTP method, status and a snippet of the response body. The full
 * sanitized log is also attached as JSON.
 */
function renderNetwork(result: ValidationResult): string[] {
  const calls = result.networkCalls ?? [];
  if (!calls.length) return [];
  const lines: string[] = ['h4. Failing Network Calls'];
  for (const e of calls.slice(0, 8)) {
    lines.push(`* {{${e.method} ${e.url}}} → *${e.status} ${e.statusText}*`);
    const body = (e.responseBody ?? '').trim();
    if (body) lines.push('{code:json}', body.slice(0, 600), '{code}');
  }
  if (calls.length > 8) {
    lines.push(`_(+${calls.length - 8} more failing call(s) in the attached network log)_`);
  }
  return lines;
}

/** Render the "Not Validated" (coverage honesty) block. */
function renderNotValidated(result: ValidationResult): string[] {
  if (!result.notValidated || !result.notValidated.length) return [];
  return ['h4. Not Validated / Out of Scope', ...result.notValidated.map(n => `* ${n}`)];
}

function blank(): string { return ''; }

type Verdict = 'pass' | 'fail' | 'inconclusive';

function verdictHeader(verdict: Verdict, envLabel: string, key: string): string {
  if (verdict === 'pass') return `h3. ✅ Tested in ${envLabel}: ${key}`;
  if (verdict === 'fail') return `h3. ❌ Testing FAILED: ${key}`;
  return `h3. ⚠️ Testing INCONCLUSIVE: ${key}`;
}

/** Shared comment builder — PASS / FAIL / INCONCLUSIVE only differ in header + a few blocks. */
function buildComment(verdict: Verdict, issue: JiraIssue, env: string, result: ValidationResult): string {
  const envLabel = env === 'CAE' ? 'CAE' : 'QA';
  const lines: string[] = [
    verdictHeader(verdict, envLabel, issue.key),
    blank(),
    `*Summary:* ${issue.summary}`,
    `*Result:* ${result.summary}`,
    blank(),
    'h4. Acceptance Criteria',
  ];

  if (result.acChecks && result.acChecks.length) {
    lines.push(...renderAcTable(result.acChecks));
  } else if (verdict === 'pass') {
    lines.push(...result.details.map(d => `* ${d} ✅`));
  } else {
    lines.push(...result.details.map(d => `* ${d}`));
  }
  lines.push(blank());

  // Repro steps only make sense when a defect was actually reproduced.
  if (verdict === 'fail' && result.reproSteps && result.reproSteps.length) {
    lines.push('h4. Repro Steps', ...result.reproSteps.map(s => `# ${s}`), blank());
  }

  // Surface failing network calls inline for any non-pass verdict — this is the
  // "network inspect" detail a bug-fixing agent needs to know where to look.
  if (verdict !== 'pass') {
    const net = renderNetwork(result);
    if (net.length) lines.push(...net, blank());
  }

  if (result.consoleErrors && result.consoleErrors.length) {
    lines.push('h4. Console Errors', '{code}', ...result.consoleErrors.slice(0, 5), '{code}', blank());
  }

  lines.push(...renderContext(result, envLabel));

  const notValidated = renderNotValidated(result);
  if (notValidated.length) lines.push(blank(), ...notValidated);

  const evidence = renderEvidence(result);
  if (evidence.length) lines.push(blank(), ...evidence);

  lines.push(blank(), `_Tested on: ${new Date().toISOString()}_`, AI_FOOTER);
  return lines.join('\n');
}

/** Build the comment text for a PASS verdict */
export function buildPassComment(issue: JiraIssue, env: string, result: ValidationResult): string {
  return buildComment('pass', issue, env, result);
}

/** Build the comment text for a FAIL verdict */
export function buildFailComment(issue: JiraIssue, env: string, result: ValidationResult): string {
  return buildComment('fail', issue, env, result);
}

/** Build the comment text for an INCONCLUSIVE run (feature could not be validated) */
export function buildInconclusiveComment(issue: JiraIssue, env: string, result: ValidationResult): string {
  return buildComment('inconclusive', issue, env, result);
}
