/**
 * ticket-runner.ts — Single entry point for ticket validation.
 *
 * Decision flow:
 *   1. Does a codified validator exist AND health is good (< 3 consecutive fails)?
 *      → Run via validateTicket() (fast, no LLM cost)
 *        FAIL 3x in a row → marks entry stale → falls back to agent on next run
 *   2. No validator OR stale?
 *      → Run via runAgentValidation() (LLM brain + CDP, works for any ticket)
 *
 * Health is persisted to scripts/validators/registry.json for codified/generated
 * validators so stale scripts don't silently keep running and wasting time.
 */

import 'dotenv/config';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { pathToFileURL } from 'url';
import { connectBrowser, disconnectBrowser } from './cdp-browser.js';
import { validateTicket, hasValidator } from './ticket-validator.js';
import { publishResult } from './publish-result.js';
import { runAgentValidation } from './agent-validate.js';
import type { JiraIssue } from './jira-client.js';
import type { ValidationResult } from './ticket-validator.js';

const REGISTRY_PATH = resolve(process.cwd(), 'scripts/validators/registry.json');
const APP_URL  = process.env.APP_URL_QA ?? 'https://your-app-qa.example.com';
const APP_URL_DEV = process.env.APP_URL_DEV?.trim() || '';
const APP_ENV  = process.env.APP_ENV    ?? 'QA';
const STALE_THRESHOLD = 3;
const MCP_FIRST = /^(1|true|yes)$/i.test(process.env.MCP_FIRST ?? 'false');
const DEV_FIRST = /^(1|true|yes)$/i.test(process.env.DEV_FIRST_DISCOVERY ?? 'false');
const LEGACY_ORACLE = /^(1|true|yes)$/i.test(process.env.LEGACY_ORACLE ?? 'false');
const LEGACY_URL = process.env.APP_URL_LEGACY?.trim() || undefined;
const ORACLE_DOCS_DIR = process.env.ORACLE_DOCS_DIR?.trim() || resolve(process.cwd(), 'wiki', 'docs');
const RESEARCH_WIKI_DOCS_DIR = process.env.RESEARCH_WIKI_DOCS_DIR?.trim() || '';

// ── Registry types & helpers ──────────────────────────────────────────────────

interface HealthEntry {
  totalRuns: number;
  passes: number;
  fails: number;
  consecutiveFails: number;
  lastRun: string | null;
  lastResult: 'pass' | 'fail' | null;
}

interface RegistryEntry {
  title: string;
  /** Relative path to the validator script (hand-written or generated). */
  scriptPath?: string;
  /** True if the script was auto-generated by agent-validate.ts. */
  generated?: boolean;
  /** ISO timestamp of auto-generation. */
  generatedAt?: string;
  health: HealthEntry;
}

function isTrackedValidator(key: string, entry?: RegistryEntry): boolean {
  if (hasValidator(key)) return true;
  return !!entry?.generated && !!entry.scriptPath;
}

function blankHealth(): HealthEntry {
  return { totalRuns: 0, passes: 0, fails: 0, consecutiveFails: 0, lastRun: null, lastResult: null };
}

function loadRegistry(): Record<string, RegistryEntry> {
  if (!existsSync(REGISTRY_PATH)) return {};
  const raw = JSON.parse(readFileSync(REGISTRY_PATH, 'utf-8')) as Record<string, unknown>;
  const { _meta: _, ...entries } = raw;
  return entries as Record<string, RegistryEntry>;
}

function saveRegistry(entries: Record<string, RegistryEntry>): void {
  const dir = dirname(REGISTRY_PATH);
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  const file = {
    _meta: {
      description: 'Health tracker for codified ticket validators. consecutiveFails >= 3 → stale → falls back to autonomous agent.',
      updated: new Date().toISOString(),
    },
    ...entries,
  };
  writeFileSync(REGISTRY_PATH, JSON.stringify(file, null, 2));
}

function recordHealth(key: string, title: string, passed: boolean): void {
  const entries = loadRegistry();
  if (!isTrackedValidator(key, entries[key])) {
    return; // Registry health is only for codified/generated validators.
  }
  if (!entries[key]) {
    entries[key] = { title, health: blankHealth() };
  }
  const h = entries[key].health;
  h.totalRuns++;
  h.lastRun = new Date().toISOString();
  h.lastResult = passed ? 'pass' : 'fail';
  if (passed) {
    h.passes++;
    h.consecutiveFails = 0;
  } else {
    h.fails++;
    h.consecutiveFails++;
  }
  saveRegistry(entries);
}

function isStale(key: string): boolean {
  const entries = loadRegistry();
  const entry = entries[key];
  if (!isTrackedValidator(key, entry)) return false;
  return !!entry && entry.health.consecutiveFails >= STALE_THRESHOLD;
}

/** Returns the registered scriptPath if a generated script exists on disk and is not stale. */
function generatedScriptPath(key: string): string | null {
  const entries = loadRegistry();
  const entry = entries[key];
  if (!entry?.generated || !entry.scriptPath) return null;
  if (entry.health.consecutiveFails >= STALE_THRESHOLD) return null;
  const absPath = resolve(process.cwd(), entry.scriptPath);
  return existsSync(absPath) ? entry.scriptPath : null;
}

// ── Public API ────────────────────────────────────────────────────────────────

export interface RunnerOutcome {
  /** Normalised verdict for finishTicket() */
  verdict: 'pass' | 'fail' | 'inconclusive' | 'blocked' | 'error';
  /** Jira status the ticket was moved to */
  movedTo?: string;
  /** Which path was taken */
  method: 'codified' | 'agent';
  /** External blocker class if verdict=blocked */
  blockerClass?: 'jira-transition' | 'cdp' | 'auth' | 'outage' | 'unknown';
  /** Error message when verdict = 'error' */
  error?: string;
}

/**
 * Validate a Jira ticket via the best available path and return a normalised outcome.
 * The caller (ticket-flow.ts) handles startTicket / finishTicket bookkeeping.
 */
export async function runTicket(issue: JiraIssue): Promise<RunnerOutcome> {
  const key = issue.key;

  // 1. Hand-written codified validator (highest priority — most reliable).
  if (hasValidator(key) && !isStale(key)) {
    return runWithCodedValidator(issue);
  }

  // 2. Auto-generated script from a previous agent PASS run.
  const genPath = generatedScriptPath(key);
  if (genPath) {
    console.log(`[Runner] ${key}: using auto-generated script`);
    return runWithGeneratedScript(issue, genPath);
  }

  // 3. Autonomous agent (also generates a script on PASS for future runs).
  if (MCP_FIRST) {
    console.log(`[Runner] ${key}: MCP_FIRST enabled — using autonomous fallback in terminal flow.`);
  }
  if (isStale(key)) {
    console.warn(`[Runner] ${key}: validator stale (${STALE_THRESHOLD} consecutive fails) — using agent`);
  } else {
    console.log(`[Runner] ${key}: no script found — using autonomous agent`);
  }
  return runWithAgent(issue);
}

/** Print a health summary for all tracked entries. */
export function printHealthReport(): void {
  const allEntries = Object.entries(loadRegistry());
  const entries = allEntries.filter(([key, entry]) => isTrackedValidator(key, entry));
  console.log('\n⚙️ Run configuration\n');
  console.log(`- DEV-first discovery: ${DEV_FIRST ? `ON (${APP_URL_DEV || 'APP_URL_DEV missing'})` : 'OFF'}`);
  console.log(`- Legacy oracle parity: ${LEGACY_ORACLE ? `ON (${LEGACY_URL || 'APP_URL_LEGACY missing'})` : 'OFF'}`);
  console.log(`- Local oracle docs: ${existsSync(ORACLE_DOCS_DIR) ? `ON (${ORACLE_DOCS_DIR})` : `OFF (${ORACLE_DOCS_DIR})`}`);
  if (RESEARCH_WIKI_DOCS_DIR) {
    console.log(`- External research docs: ${existsSync(RESEARCH_WIKI_DOCS_DIR) ? `ON (${RESEARCH_WIKI_DOCS_DIR})` : `OFF (${RESEARCH_WIKI_DOCS_DIR})`}`);
  }

  if (!entries.length) {
    console.log('No entries in registry yet.');
    return;
  }
  console.log('\n📊 Validator Registry Health\n');
  console.log('Ticket    | Type      | Title                                | Runs | Pass% | Status');
  console.log('----------|-----------|--------------------------------------|------|-------|-------');
  for (const [key, entry] of entries) {
    const h = entry.health;
    const rate = h.totalRuns ? Math.round((h.passes / h.totalRuns) * 100) : 0;
    const status = h.consecutiveFails >= STALE_THRESHOLD ? '🔴 STALE' : h.lastResult === 'pass' ? '🟢 OK' : h.lastResult === 'fail' ? '🟡 FAIL' : '⬜ NEW';
    const type = entry.generated ? '🤖 generated' : '✍️  codified ';
    console.log(
      `${key.padEnd(9)} | ${type} | ${(entry.title ?? '').slice(0, 36).padEnd(36)} | ${String(h.totalRuns).padStart(4)} | ${String(rate + '%').padStart(5)} | ${status}`,
    );
  }
  const ignored = allEntries.length - entries.length;
  if (ignored > 0) {
    console.log(`[Runner] Ignored ${ignored} non-codified ticket entr${ignored === 1 ? 'y' : 'ies'} in registry.`);
  }
  console.log('');
}

// ── Internal paths ────────────────────────────────────────────────────────────

async function runWithCodedValidator(issue: JiraIssue): Promise<RunnerOutcome> {
  const key = issue.key;
  console.log(`[Runner] ${key}: using codified validator`);

  const session = await connectBrowser();
  try {
    const result = await validateTicket(session.page, issue, APP_URL);
    await disconnectBrowser(session);

    const outcome = await publishResult(issue, result, { env: APP_ENV });
    const passed = outcome.verdict === 'pass';
    recordHealth(key, issue.summary, passed);

    const verdict = outcome.blockedReason ? 'blocked'
      : outcome.verdict === 'pass' ? 'pass'
      : outcome.verdict === 'inconclusive' ? 'inconclusive'
      : 'fail';
    return {
      verdict,
      movedTo: outcome.movedTo ?? undefined,
      method: 'codified',
      blockerClass: outcome.blockedReason ? 'jira-transition' : undefined,
      error: outcome.blockedReason ?? undefined,
    };

  } catch (err) {
    await disconnectBrowser(session).catch(() => { /* best-effort */ });
    const msg = err instanceof Error ? err.message : String(err);

    // PENDING = no validator body — shouldn't reach here but guard just in case.
    if (msg.includes('[PENDING]')) {
      return { verdict: 'error', method: 'codified', error: msg };
    }

    recordHealth(key, issue.summary, false);

    // If this failure makes the validator stale, fall back to the agent right now.
    if (isStale(key)) {
      console.warn(`[Runner] ${key}: just became stale — falling back to agent this run`);
      return runWithAgent(issue);
    }

    return { verdict: 'error', method: 'codified', error: msg };
  }
}

async function runWithGeneratedScript(issue: JiraIssue, scriptPath: string): Promise<RunnerOutcome> {
  const key = issue.key;
  const absPath = resolve(process.cwd(), scriptPath);
  const session = await connectBrowser();
  try {
    const mod = await import(pathToFileURL(absPath).href);
    const validateFn = mod.validate as ((page: unknown, issue: JiraIssue) => Promise<ValidationResult>) | undefined;
    if (typeof validateFn !== 'function') {
      throw new Error(`Generated script ${scriptPath} does not export a validate() function.`);
    }

    const result = await validateFn(session.page, issue);
    await disconnectBrowser(session);

    const outcome = await publishResult(issue, result, { env: APP_ENV });
    const passed = outcome.verdict === 'pass';
    recordHealth(key, issue.summary, passed);

    if (!passed && isStale(key)) {
      console.warn(`[Runner] ${key}: generated script just became stale — agent will regenerate on next PASS`);
    }

    const verdict = outcome.blockedReason ? 'blocked'
      : outcome.verdict === 'pass' ? 'pass'
      : outcome.verdict === 'inconclusive' ? 'inconclusive'
      : 'fail';
    return {
      verdict,
      movedTo: outcome.movedTo ?? undefined,
      method: 'codified',
      blockerClass: outcome.blockedReason ? 'jira-transition' : undefined,
      error: outcome.blockedReason ?? undefined,
    };

  } catch (err) {
    await disconnectBrowser(session).catch(() => { /* best-effort */ });
    const msg = err instanceof Error ? err.message : String(err);
    recordHealth(key, issue.summary, false);

    if (isStale(key)) {
      console.warn(`[Runner] ${key}: generated script stale after error — falling back to agent`);
      return runWithAgent(issue);
    }
    return { verdict: 'error', method: 'codified', error: msg };
  }
}

async function runWithAgent(issue: JiraIssue): Promise<RunnerOutcome> {
  console.log(`[Runner] ${issue.key}: using autonomous agent`);
  try {
    if (DEV_FIRST && APP_URL_DEV) {
      console.log(`[Runner] ${issue.key}: DEV-first discovery at ${APP_URL_DEV} (no publish)`);
      const discovery = await runAgentValidation(issue, {
        appUrl: APP_URL_DEV,
        appEnv: 'DEV',
        publish: false,
        noTransition: true,
        legacyOracle: false,
      });
      console.log(`[Runner] ${issue.key}: DEV discovery verdict=${discovery.verdict}`);
    }

    const outcome = await runAgentValidation(issue, {
      appUrl: APP_URL,
      appEnv: APP_ENV,
      legacyOracle: LEGACY_ORACLE,
      legacyUrl: LEGACY_URL,
    });
    const verdict = outcome.blockedReason ? 'blocked'
      : outcome.verdict === 'pass' ? 'pass'
      : outcome.verdict === 'inconclusive' ? 'inconclusive'
      : 'fail';
    return {
      verdict,
      movedTo: outcome.movedTo,
      method: 'agent',
      blockerClass: outcome.blockedReason ? 'jira-transition' : undefined,
      error: outcome.blockedReason ?? undefined,
    };
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    if (msg.startsWith('RATE_LIMIT_EXHAUSTED')) throw err; // let batch runner handle cooldown
    return { verdict: 'error', method: 'agent', error: msg };
  }
}
